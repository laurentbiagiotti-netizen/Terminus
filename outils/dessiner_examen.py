def grille(dessin):
    """Un portrait dessiné dans la grille 88 x 85 (comme dessiner_panne.perso), posé en x2 sur la toile W x H."""
    g = Image.new('P', (88, 85), N); g.putpalette(PAL); gd = ImageDraw.Draw(g)

    def r(x0, y0, x1, y1, c):
        gd.rectangle([x0, y0, x1, y1], fill=c)
    dessin(r)
    return g.resize((W, H), Image.NEAREST)


